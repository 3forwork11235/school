// a3·x³ + a2·x² + a1·x + a0
function cub(a3, a2, a1, a0) {
  const parts = [];
  [[a3, 'x³'], [a2, 'x²'], [a1, 'x'], [a0, '']].forEach(([k, v]) => {
    if (!k) return;
    const ab = Math.abs(k), c = v && ab === 1 ? '' : ab;
    parts.push((parts.length ? (k < 0 ? ' − ' : ' + ') : (k < 0 ? '−' : '')) + c + v);
  });
  return parts.join('') || '0';
}
// f(x) = x³ + A x² + B x с экстремумами в m и n (m + n чётно)
function cubicExt() {
  let m, n;
  do { m = R.ri(-4, 3); n = R.ri(m + 2, 4); } while ((m + n) % 2 !== 0);
  return { m: m, n: n, A: -3 * (m + n) / 2, B: 3 * m * n };
}

