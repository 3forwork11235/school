function sub(a, n) { return a + '<sub>' + n + '</sub>'; }
const TIMES = ['', '', 'два раза', 'три раза', 'четыре раза'];
function fact(n) { let r = 1; for (let i = 2; i <= n; i++) r *= i; return r; }
function comb(n, k) { return Math.round(fact(n) / (fact(k) * fact(n - k))); }

